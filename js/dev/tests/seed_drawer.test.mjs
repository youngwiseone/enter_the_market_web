import assert from 'node:assert/strict';
import { getSeedDrawerChoices } from '../../ui/seed_drawer.js';
const state = { player:{}, items:[{id:4,name:'Carrot',type:'produce'},{id:5,name:'Potato',type:'produce'},{id:2,name:'Tomato',type:'produce'},{id:31,name:'Sprinkler',type:'sprinkler'}], shop:[{itemId:5,price:2},{itemId:4,price:1.30},{itemId:2,price:3},{itemId:31,price:7}] };
const query = () => getSeedDrawerChoices({ state, isShopItemUnlocked: id=>id!==2, getFreePurchaseCount: id=>id===5?1:0 });
const original = JSON.stringify(state);
assert.deepEqual(query().map(({ name,price,freeCount })=>[name,price,freeCount]),[['Carrot',1.3,0],['Potato',2,1]]);
assert.equal(JSON.stringify(state),original);
state.player.openingTrade={carrotAvailable:true};
assert.deepEqual(query(),[]);
state.player.openingTrade={carrotAvailable:false};
assert.deepEqual(query(),[]);
state.player.openingTrade.lastSale={profit:-1};
assert.equal(query().length,2);
state.shop[1].price=1.70;
assert.equal(query()[0].price,1.70);
console.log('The seed drawer shows only unlocked produce, with current prices and free seed offers, after the opening sale.');

const tomatoGoal = { id:'tomato-first-harvest', reward:{freePurchases:{itemId:2,count:2}} };
state.goals=[{id:'unrelated',reward:{freePurchases:{itemId:4,count:7}}}, tomatoGoal];
state.goalsClaimed={};
let freeTomatoes=0;
const all = () => getSeedDrawerChoices({state,isShopItemUnlocked:()=>true,getFreePurchaseCount:id=>id===2?freeTomatoes:0});
assert.deepEqual(all().map(choice=>choice.firstSaleFreeCount),[0,0,2]);
assert.equal(all().at(-1).freeCount,0);
tomatoGoal.enabled=false;
assert.equal(all().at(-1).firstSaleFreeCount,0);
tomatoGoal.enabled=true;
state.goalsClaimed[tomatoGoal.id]=true;
freeTomatoes=2;
assert.equal(all().at(-1).firstSaleFreeCount,0);
assert.equal(all().at(-1).freeCount,2);
freeTomatoes=1;
assert.equal(all().at(-1).freeCount,1);
freeTomatoes=0;
assert.equal(all().at(-1).firstSaleFreeCount,0);
assert.equal(all().at(-1).price,3);
